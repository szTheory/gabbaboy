#!/usr/bin/env python3
"""Independent CGB layer-priority oracle (Phase 11, D-22, GB-CPU-002).

Written from the Pan Docs rule text (Tile_Maps.html, OAM.html, LCDC.html), never from the
emulator core. The rules, as prose:

  * Object colour index 0 is transparent.
  * CGB mode (cartridge $143 bit 7): LCDC.0 is a master priority switch, not a BG enable. The BG is
    always drawn. Objects are ordered by OAM index only: the lowest OAM index with an opaque pixel
    is the candidate. The candidate wins over the BG unless LCDC.0 = 1 and (OAM attribute bit 7 or
    BG map attribute bit 7) and the BG colour index is 1-3. LCDC.0 = 0 therefore always shows the
    object when it is opaque.
  * Compatibility mode: LCDC.0 is the BG enable (BG index reads as 0 when clear). BG map attribute
    bit 7 is ignored. Objects are ordered by X, lower OAM index on ties. The candidate wins unless
    OAM attribute bit 7 is set and the effective BG index is 1-3.

Object A always has the lower OAM index than object B. `order` is 0 when A.x < B.x, 1 when equal,
2 when A.x > B.x.

Modes: --write PATH | --check PATH | --self-test. Standard library only.
"""
import itertools
import sys

COLUMNS = ("mode", "lcdc0", "bg_attr7", "bg_index", "a_index", "a_pri", "b_index", "b_pri", "order")
DOMAINS = ((0, 1), (0, 1), (0, 1), range(4), range(4), (0, 1), range(4), (0, 1), range(3))
ROWS = 6144


def expect(row, mutant=None):
    """Return (layer, index): layer 0 = BG, 1 = object A, 2 = object B."""
    mode, lcdc0, bg_attr7, bg_index, a_index, a_pri, b_index, b_pri, order = row
    a_opaque = a_index != 0
    b_opaque = b_index != 0
    compat = mode == 1
    if mutant == "cgb_x_order":
        compat_order = True
    else:
        compat_order = compat
    if a_opaque and b_opaque:
        if compat_order:
            winner = 2 if order == 2 else 1
        else:
            winner = 1
    elif a_opaque:
        winner = 1
    elif b_opaque:
        winner = 2
    else:
        winner = 0
    if compat and lcdc0 == 0 and mutant != "compat_ignore_lcdc0":
        effective_bg = 0
    else:
        effective_bg = bg_index
    if winner == 0:
        return (0, effective_bg)
    pri = a_pri if winner == 1 else b_pri
    index = a_index if winner == 1 else b_index
    if not compat:
        attr = 0 if mutant == "cgb_ignore_bg_attr" else bg_attr7
        behind = lcdc0 == 1 and (pri == 1 or attr == 1) and bg_index != 0
    else:
        behind = pri == 1 and effective_bg != 0
    if behind:
        return (0, effective_bg)
    return (winner, index)


def all_rows():
    return list(itertools.product(*DOMAINS))


def render(mutant=None):
    lines = [
        "/* Generated by tests/scripts/gen-cgb-priority-truth.py. Do not edit.",
        " * Independent priority oracle written from Pan Docs Tile_Maps.html, OAM.html and",
        " * LCDC.html; it never reads emulator code (D-22, GB-CPU-002).",
        " * Fields: mode(0 CGB,1 compat) lcdc0 bg_attr7 bg_index a_index a_pri b_index b_pri",
        " * order(0 A.x<B.x,1 equal,2 A.x>B.x) expect_layer(0 BG,1 A,2 B) expect_index.",
        " * Rows: 6144. */",
        "#define GBB_CGB_PRIORITY_TRUTH_ROWS 6144",
    ]
    for row in all_rows():
        layer, index = expect(row, mutant)
        lines.append("{" + ",".join(str(v) for v in row) + ",%d,%d}," % (layer, index))
    return "\n".join(lines) + "\n"


def check(path):
    with open(path, "r", encoding="utf-8") as handle:
        have = handle.read().split("\n")
    want = render().split("\n")
    for number in range(max(len(have), len(want))):
        left = have[number] if number < len(have) else None
        right = want[number] if number < len(want) else None
        if left != right:
            print("cgb-priority-truth mismatch line=%d" % (number + 1))
            return 1
    print("cgb-priority-truth check pass rows=%d" % len(all_rows()))
    return 0


def self_test():
    rows = all_rows()
    product = 1
    for domain in DOMAINS:
        product *= len(list(domain))
    if len(rows) != product or product != ROWS:
        print("cgb-priority-truth self-test fail rows=%d product=%d" % (len(rows), product))
        return 1
    table = {row: expect(row) for row in rows}
    for column, name in enumerate(COLUMNS):
        sensitive = False
        for row, out in table.items():
            for value in DOMAINS[column]:
                other = row[:column] + (value,) + row[column + 1:]
                if table[other] != out:
                    sensitive = True
                    break
            if sensitive:
                break
        if not sensitive:
            print("cgb-priority-truth self-test fail inert=%s" % name)
            return 1
    for mutant in ("cgb_ignore_bg_attr", "cgb_x_order", "compat_ignore_lcdc0"):
        if not any(expect(row, mutant) != out for row, out in table.items()):
            print("cgb-priority-truth self-test fail mutant-undetected=%s" % mutant)
            return 1
    print("cgb-priority-truth self-test pass inputs=%d" % len(COLUMNS))
    return 0


def main(argv):
    if len(argv) == 3 and argv[1] == "--write":
        with open(argv[2], "w", encoding="utf-8", newline="\n") as handle:
            handle.write(render())
        return 0
    if len(argv) == 3 and argv[1] == "--check":
        return check(argv[2])
    if len(argv) == 2 and argv[1] == "--self-test":
        return self_test()
    print("usage: gen-cgb-priority-truth.py --write PATH | --check PATH | --self-test", file=sys.stderr)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv))
